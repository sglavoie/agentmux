// This file classifies a GitHub Copilot CLI screen scrape. It is the third
// adapter alongside claude.go and codex.go, and it is deliberately the smallest
// of the three, for a reason that is a design decision rather than an omission.
//
// THE COPY IS CAPTURE-DERIVED. patterns_copilot.toml's wording was rewritten
// from `kitten @ get-text --extent=screen` captures of GitHub Copilot CLI
// 1.0.82, committed byte-for-byte under testdata/ and each named in a
// copilot_adapter_test.go row. It replaced provisional copy written by analogy
// to Claude and Codex, which was wrong in kind rather than mis-tuned in all
// three clauses — see the header of that test file for what each placeholder
// got wrong and which build a re-capture is owed to.
//
// ---------------------------------------------------------------------------
// COMPOSITION WITH THE TRANSCRIPT PROBE: the screen REFUSES, the transcript
// SETTLES.
// ---------------------------------------------------------------------------
//
// Copilot already has an evidence path, and a good one:
// internal/daemon/copilot_transcript_probe.go reads Copilot's own JSONL session
// transcript, requires a terminal lifecycle event to hold steady across two
// probe observations at the same transcript generation, re-checks at apply time
// that nothing was appended in between, and self-heals its own synthetic stop
// when a record lands after the check. That is authoritative structured
// evidence about whether the turn ended, generated by the harness itself.
//
// A screen cannot beat it at that question, and this adapter does not try. It
// reports Working, Blocked or Unknown and NEVER Terminal — there is no positive
// terminal clause to consult, on any pattern set, so SettleableTerminal() is
// false for every observation it can produce. Three reasons, in order of how
// much they would cost to get wrong:
//
//  1. Two positive-evidence paths for one question is a second precedence
//     system. doc.go names that as the thing this package must not grow, and it
//     would be true here in the concrete: a screen whose completion marker has
//     scrolled away and a transcript whose turn_end is stable disagree about a
//     pane, and nothing would arbitrate.
//  2. internal/daemon/activity/policy.go's sample table already records
//     "Copilot stays out of the table ON PURPOSE", because the Copilot probe's
//     Generation is a transcript byte size rather than a screen fingerprint. A
//     Terminal Copilot observation would MISS that table and fall to
//     IdleMinimumSamples, silently spending fewer samples than either wired
//     harness — the fail-closed miss path doing the opposite of its job.
//  3. There is nothing to gain. The transcript already settles the pane; a
//     screen agreeing with it changes no icon.
//
// What the screen has that the transcript does not is the pane RIGHT NOW. A
// Copilot session sitting on a tool-permission prompt has written its records
// and stopped writing: the prompt is not a transcript event, so the tail can
// read terminal while a human is being waited on. A live status line and a
// composer holding queued input are the same shape of fact. So the screen is
// admitted in exactly the direction where it is strictly stronger, as a veto:
//
//	YES — the screen's VetoBlockingPrompt (and every other veto here) may
//	refuse a transcript-driven settle. It is the same argument that put the
//	Claude and Codex screen paths in front of their hook paths: a visible
//	prompt outranks a silent record.
//
// That refusal IS wired, at the seam this paragraph used to only name:
// copilotScreenRefusesSettle, called beside the `evidence.State !=
// CopilotLifecycleTerminal` test in probeCopilotTranscriptWindow. It is not in
// copilotTranscriptStopProbeCanOverwrite — that is an ICON filter consulted by
// both the settle and the recovery gate, and it stays unchanged (there is a
// paragraph there saying so). The placement is what makes the refusal
// FORWARD-ONLY: recovery of a stranded synthetic 🛑 returns before it, because
// recovery un-settles rather than settles and a blocked pane must not be left
// wearing a stop its own transcript disagrees with. Every veto refuses, not
// just VetoBlockingPrompt, and so does a failed screen read.
//
// Two consequences of the refusal-only contract are load-bearing there. Wiring
// the screen in can only ever REMOVE settles, never add one, so the worst a
// mistake here can do is strand a pane on a ⚡ that its next real turn clears.
// And the direction of that risk is why the copy had to be capture-derived
// first: a wrong blocking_prompt or composer_line would refuse EVERY Copilot
// settle, since a finished Copilot turn renders no completion marker at all and
// the veto-free reading is the ordinary case.

// The UI copy this adapter keys on lives in patterns_copilot.toml, loaded by
// patterns.go and overridable per user. The clause names below are the contract
// between that file and this one; each is documented at its definition site.
//
// FAIL-CLOSED ORIENTATION. A clause the installed set does not define reports no
// match. For composer_line that direction is safe on its own — a missing one
// vetoes with VetoComposerBusy — but for every clause that FEEDS a veto it is
// the wrong way round: no match means no veto. Since this adapter never settles,
// a lost veto here cannot settle a live pane by itself; what it CAN do, once the
// refusal above is wired, is silently stop refusing a transcript settle that
// should have been refused. That is the same class of silent loss the other two
// adapters guard, so it is guarded the same way — copilotRequirements below.
//
// There is deliberately no background_task clause. Claude has one because it
// renders a "ctrl+b to …" manager hint, and Codex has a background-terminal
// footer; whether Copilot has any such affordance is unknown, and a veto clause
// invented for a screen nobody has read is a guess wearing a safety property.
const (
	copilotClauseComposerLine   = "composer_line"
	copilotClauseChoiceLine     = "choice_line"
	copilotClauseWorking        = "working_status_line"
	copilotClauseInterruptHint  = "interrupt_hint"
	copilotClauseBlockingPrompt = "blocking_prompt"
)

// copilotRequirements is the subset of the clauses above whose absence is not
// merely a lost check but a lost REFUSAL. Every one of them is the sole source
// of a veto — which is the whole test for membership, and the list is short only
// because this adapter has no positive evidence to also carry.
//
// Getting this list right matters more than getting the patterns right. A
// pattern that is merely wrong stops matching, and a fixture notices. A missing
// requirement means an override that DELETES a refusal still installs: the file
// parses, the daemon starts, doctor reports a valid override, and the only
// symptom is a veto that no longer fires. So the rule is mechanical rather than
// judged — if a clause is the only thing that can raise a Veto bit, it belongs
// here — and TestCopilotRequirementsCoverEverySoleVetoSource re-derives the list
// from the adapter's actual behaviour rather than trusting this comment.
//
// Nothing is left out. Both other adapters exclude their positive-evidence
// clauses, on the argument that losing one costs a settle it would otherwise
// have made and an override predating a new marker shape must keep working.
// This adapter has no positive-evidence clauses at all, so that exemption has
// nothing to apply to and every clause it reads is required.
//
// Two things consume this list. patterns.go refuses to INSTALL an override that
// does not satisfy it, which is where a real user's mistake is caught, and it
// holds the embedded file to the same contract, which is what makes shipping
// provisional copy safe: a placeholder that lost a clause to a rename fails the
// build's own tests rather than shipping a classifier that cannot refuse.
// Classify does NOT re-check it; see the note in Classify for why that is a
// difference from claude.go rather than an oversight.
var copilotRequirements = patternset.Requirements{
	{
		Name: copilotClauseWorking, Kind: patternset.RegexClause,
		Reason: "it is the only source of the live-status veto, so without it a running turn " +
			"on an empty composer raises nothing and a transcript settle is never refused",
	},
	{
		Name: copilotClauseComposerLine, Kind: patternset.AnyClause,
		Reason: "it is the only evidence a pane is sitting at a ready prompt; without it every " +
			"screen is composer_busy, which withholds every refusal-bearing reading of the pane",
	},
	{
		Name: copilotClauseChoiceLine, Kind: patternset.AnyClause,
		Reason: "it is half the blocking-prompt veto, and the half that survives a reworded prompt",
	},
	{
		Name: copilotClauseBlockingPrompt, Kind: patternset.AnyClause,
		Reason: "it is the other half of the blocking-prompt veto; without both, a pane waiting " +
			"on a permission answer looks quiet to the screen and the transcript settles it",
	},
	{
		Name: copilotClauseInterruptHint, Kind: patternset.AnyClause,
		Reason: "it is the only source of the interrupt-hint veto, the backstop for a live turn " +
			"whose status line this set does not recognize",
	},
}

// copilotAdapter is the GitHub Copilot CLI screen adapter.
type copilotAdapter struct {
	// Patterns pins this adapter to one pattern set. The registered adapter
	// leaves it zero and resolves the installed set per Classify instead:
	// the adapters map is built at package init and read lock-free by For(),
	// so a set captured into it would be the embedded default forever and
	// Load's override would have no effect. Tests set it to classify against
	// a pattern set without installing one globally.
	Patterns Patterns
}

// Harness returns Copilot's canonical harness name.
func (copilotAdapter) Harness() string { return harness.Copilot }

// patterns resolves the pattern set this Classify call reads.
func (a copilotAdapter) patterns() Patterns {
	if a.Patterns.Harness() != "" {
		return a.Patterns
	}
	set, _ := PatternsFor(harness.Copilot)
	return set
}

// Classify reads a Copilot screen capture.
//
// The Adapter contract holds here exactly as it does for Claude and Codex:
// every veto is computed FIRST and UNCONDITIONALLY, and positive terminal
// evidence is consulted only on a veto-free screen. Nothing short-circuits,
// because the Observation names every veto for diagnostics.
//
// The second half of that contract is satisfied vacuously and on purpose: a
// veto-free Copilot screen is consulted for positive terminal evidence, finds
// none defined, and comes back Unknown. This adapter has no Terminal branch at
// all — see the composition decision at the top of this file — so the ordering
// cannot be inverted here even by mistake, and TierNone is the only tier it can
// report. TestCopilotAdapterNeverSettles pins that as the invariant it is.
//
// Both Unknown paths below are the same fail-closed answer reached two ways: a
// composer-busy screen (queued input, or a capture scrolled past its composer)
// and a veto-free screen say equally little about the turn. They are not
// collapsed into one branch because the veto SET distinguishes them for whoever
// is reading a declined observation, which is the whole point of keeping vetoes
// as a set rather than a first hit.
func (a copilotAdapter) Classify(screen string) Observation {
	patterns := a.patterns()
	lower := strings.ToLower(screen)
	statusLine := copilotLatestWorkingLine(patterns, screen)

	var vetoes Veto
	if statusLine != "" {
		vetoes |= VetoLiveStatusLine
	}
	// A one-way veto: Copilot rendering no interrupt hint is not evidence a turn
	// ended, which is the lesson claude.go's legacy backstop records.
	if patterns.Match(copilotClauseInterruptHint, screen, lower) {
		vetoes |= VetoInterruptHint
	}
	if copilotScreenHasBlockingPrompt(patterns, lower, screen) {
		vetoes |= VetoBlockingPrompt
	}
	if !patterns.Match(copilotClauseComposerLine, screen, lower) {
		vetoes |= VetoComposerBusy
	}
	// No VetoContextLimit. internal/contextlimit holds CLAUDE's recovery-banner
	// copy — claude.go is its only adapter caller — and running a Copilot screen
	// through it would be the confident-wrong-answer For() refuses to make.
	//
	// No copilotRequirements.Satisfied gate either, and that IS the difference
	// from claude.go worth naming. Claude re-checks its requirements inside
	// Classify so an incomplete set cannot SETTLE a pane through a public seam
	// the loader never saw. There is no settle here to guard: an incomplete set
	// loses vetoes and lands on Unknown, which is already the fail-closed answer
	// a Satisfied gate would produce. Adding the branch would be a check that
	// cannot change an outcome, and a reader would reasonably infer it protects
	// something. TestCopilotIncompleteSetStillCannotSettle pins the equivalence
	// so this stops being true loudly if a Terminal branch is ever added.

	observation := Observation{
		Vetoes:      vetoes,
		Fingerprint: Fingerprint(screen),
		StatusLine:  boundStatusLine(statusLine),
	}
	switch {
	case vetoes&VetoBlockingPrompt != 0:
		// A screen waiting on the user is reported as such even when it also
		// carries a working hint; "blocked" is the more actionable reading and
		// neither one settles.
		observation.State = Blocked
	case vetoes&(VetoLiveStatusLine|VetoInterruptHint) != 0:
		observation.State = Working
	default:
		observation.State = Unknown
	}
	return observation
}

// copilotLatestWorkingLine returns the LAST line matching the working clause, or
// "" when none does. Latest-wins mirrors claudeLatestStatusLine and is what makes
// a resumed turn readable: a marker from a previous turn scrolled above the
// current one must not outvote the live status line below it.
//
// The clause is resolved once, outside the loop, because it is the same regex
// for every line — externalizing the patterns must not turn a per-screen scan
// into a per-line map lookup. The regex uses a bare ^ rather than (?m), so this
// must feed it one line at a time.
func copilotLatestWorkingLine(patterns Patterns, screen string) string {
	working := patterns.Regexp(copilotClauseWorking)
	text := ""
	for _, line := range strings.Split(screen, "\n") {
		if matchesLine(working, line) {
			text = line
		}
	}
	return text
}

// copilotScreenHasBlockingPrompt reports whether the screen shows a permission,
// elicitation, or other user-blocking choice prompt.
//
// The phrase list is English-only and exhaustive by construction; it lives in
// patterns_copilot.toml so that limitation has a single home a user can widen
// without a build. The disjunction with the choice-line shape stays here: which
// clauses combine, and how, is Go's. lower is passed in because the caller
// already folded the screen once.
func copilotScreenHasBlockingPrompt(patterns Patterns, lower, screen string) bool {
	return patterns.Match(copilotClauseBlockingPrompt, screen, lower) ||
		patterns.Match(copilotClauseChoiceLine, screen, lower)
}
