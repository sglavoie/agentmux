// Package aslcontract vendors the ASL-owned compatibility corpus and exposes
// the one contract-set identity this build implements.
//
// agent-session-loop is the sole authority for what the two processes exchange:
// it owns the schemas, the fixtures that pin them, and the digest over those
// bytes that names the set. Agent Mux does not get a vote, so this package
// holds a byte-identical copy rather than a Go restatement — a restatement is a
// second source of truth, and two sources of truth is the drift the corpus
// exists to prevent.
//
// The copy is checked two ways. Offline, in `just check`, contract_test.go
// recomputes every file digest against the vendored manifest and re-derives the
// contract-set ID from the corpus bytes, so a vendored file edited on this side
// fails here. Against a live peer, `just asl-integration` asserts the installed
// bridge's hello names exactly ContractSetID, so a copy that has fallen behind
// ASL fails there. Neither check can be satisfied by a stale copy that merely
// agrees with itself.
package aslcontract

import (
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io/fs"
	"path"
	"sort"
	"strings"
)

//go:embed corpus
var embedded embed.FS

const (
	// ContractSetID is the contract set this build implements, and the only one
	// it accepts. It is pinned here rather than read from the manifest at init
	// so that a vendored manifest edited without its corpus fails a test instead
	// of silently redefining what this daemon claims to speak.
	ContractSetID = "asl-amx-1.85ec3041b9f03f47"

	// Prefix is the family every contract-set ID carries. It is a format check
	// and nothing more: a peer inside the family whose digest differs is exactly
	// as incompatible as one outside it, because the digest is the contract.
	Prefix = "asl-amx-1."

	// contractSetIDHexChars is how much of the corpus digest the ID carries.
	contractSetIDHexChars = 16

	// manifestName is excluded from the digest: it carries that digest, so
	// including it would make the identity depend on itself.
	manifestName = "manifest.json"

	// corpusRoot is the embedded directory holding the vendored copy.
	corpusRoot = "corpus"
)

// Component names, matching the manifest's own keys.
const (
	ComponentBridgeProtocol = "bridge_protocol"
	ComponentLifecycleHook  = "lifecycle_hook"
	ComponentProjection     = "projection"
)

// Fixture directories, matching the corpus layout.
const (
	FixturesBridgeProtocol = "bridge-protocol-v2"
	FixturesLifecycleHook  = "lifecycle-hook-v2"
	FixturesProjection     = "projection-v1"
)

// Manifest is the derived half of the corpus: the identity, the capability
// vocabularies both ends branch on, and the per-file digests that pin the
// bytes. Unknown fields are tolerated here on purpose — the manifest is
// generated by ASL and may grow fields Agent Mux has no use for, and the
// authority for "did the corpus change" is the digest, not this decode.
type Manifest struct {
	CurrentContractSetID string            `json:"current_contract_set_id"`
	ContractSets         []ContractSet     `json:"contract_sets"`
	Files                map[string]string `json:"files"`
	ManifestVersion      int               `json:"manifest_version"`
}

// ContractSet is one published set. Only the current one is ever adopted.
type ContractSet struct {
	ContractSetID string               `json:"contract_set_id"`
	CorpusDigest  string               `json:"corpus_digest"`
	Status        string               `json:"status"`
	Capabilities  Capabilities         `json:"capabilities"`
	Components    map[string]Component `json:"components"`
}

// Capabilities is the closed vocabulary each side validates against. Protocol 2
// splits methods, events, and the mutating subset of the methods into three
// lists, because one mixed list left "can I call this?" and "will I be sent
// this?" indistinguishable and the subset that needs a handshake implicit.
type Capabilities struct {
	BridgeErrorCodes      []string `json:"bridge_error_codes"`
	BridgeEvents          []string `json:"bridge_events"`
	BridgeMethods         []string `json:"bridge_methods"`
	BridgeMutationMethods []string `json:"bridge_mutation_methods"`
	LifecycleEvents       []string `json:"lifecycle_events"`
	LifecyclePhases       []string `json:"lifecycle_phases"`
	ProjectionPhases      []string `json:"projection_phases"`
}

// Component is one schema inside the set.
type Component struct {
	Digest           string   `json:"digest"`
	FixtureCount     int      `json:"fixture_count"`
	MaxDocumentBytes int      `json:"max_document_bytes"`
	Roots            []string `json:"roots"`
	SchemaPath       string   `json:"schema_path"`
	SchemaVersion    int      `json:"schema_version"`
}

// FS returns the vendored corpus rooted at its top directory, so a caller
// addresses `manifest.json` and `fixtures/...` exactly as the ASL repository
// spells them.
func FS() fs.FS {
	sub, err := fs.Sub(embedded, corpusRoot)
	if err != nil {
		// Unreachable: the directory is embedded at compile time.
		panic("aslcontract: corpus is not embedded: " + err.Error())
	}
	return sub
}

// ReadManifest decodes the vendored manifest.
func ReadManifest() (Manifest, error) {
	raw, err := fs.ReadFile(FS(), manifestName)
	if err != nil {
		return Manifest{}, fmt.Errorf("aslcontract: reading %s: %w", manifestName, err)
	}
	var manifest Manifest
	if err := json.Unmarshal(raw, &manifest); err != nil {
		return Manifest{}, fmt.Errorf("aslcontract: decoding %s: %w", manifestName, err)
	}
	return manifest, nil
}

// Current returns the manifest's current contract set.
func (m Manifest) Current() (ContractSet, error) {
	for _, set := range m.ContractSets {
		if set.ContractSetID == m.CurrentContractSetID {
			return set, nil
		}
	}
	return ContractSet{}, fmt.Errorf(
		"aslcontract: manifest names %q as current but publishes no such set", m.CurrentContractSetID)
}

// CorpusFiles lists every canonical corpus file as a sorted slash-separated
// path relative to the corpus root, with the manifest excluded.
func CorpusFiles() ([]string, error) {
	var names []string
	err := fs.WalkDir(FS(), ".", func(name string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasSuffix(name, ".json") || path.Base(name) == manifestName {
			return nil
		}
		names = append(names, name)
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("aslcontract: walking the corpus: %w", err)
	}
	sort.Strings(names)
	return names, nil
}

// FileDigests returns the SHA-256 of every canonical corpus file.
func FileDigests() (map[string]string, error) {
	names, err := CorpusFiles()
	if err != nil {
		return nil, err
	}
	digests := make(map[string]string, len(names))
	for _, name := range names {
		raw, err := fs.ReadFile(FS(), name)
		if err != nil {
			return nil, fmt.Errorf("aslcontract: reading %s: %w", name, err)
		}
		sum := sha256.Sum256(raw)
		digests[name] = hex.EncodeToString(sum[:])
	}
	return digests, nil
}

// CorpusDigest re-derives the identity from the vendored bytes, using ASL's
// construction: the pre-image is "<relative path>\n<sha256 hex>\n" per file in
// ascending path order. The path is part of the pre-image, so a renamed file
// moves the digest even when its bytes do not.
func CorpusDigest() (string, error) {
	digests, err := FileDigests()
	if err != nil {
		return "", err
	}
	names := make([]string, 0, len(digests))
	for name := range digests {
		names = append(names, name)
	}
	sort.Strings(names)
	var joined strings.Builder
	for _, name := range names {
		fmt.Fprintf(&joined, "%s\n%s\n", name, digests[name])
	}
	sum := sha256.Sum256([]byte(joined.String()))
	return hex.EncodeToString(sum[:]), nil
}

// DerivedContractSetID returns the contract-set ID the vendored bytes imply.
// It is what ContractSetID is checked against offline.
func DerivedContractSetID() (string, error) {
	digest, err := CorpusDigest()
	if err != nil {
		return "", err
	}
	return Prefix + digest[:contractSetIDHexChars], nil
}

// Schema is the vendored JSON Schema for one component, decoded far enough for
// Go to reuse the parts it can enforce natively. Agent Mux does not run a JSON
// Schema validator — ASL does that, over this same file, in its own suite. What
// this type gives the Go side is the closed vocabularies and the body-isolation
// rules, so a Go constant list is checked against ASL's own enum rather than
// against a second copy of it.
type Schema struct {
	Component              string                     `json:"component"`
	Version                int                        `json:"version"`
	MaxDocumentBytes       int                        `json:"max_document_bytes"`
	Roots                  map[string]string          `json:"roots"`
	BodyBearingPointers    []string                   `json:"body_bearing_pointers"`
	ForbiddenPropertyNames []string                   `json:"forbidden_property_names"`
	Definitions            map[string]json.RawMessage `json:"definitions"`
}

// ReadSchema loads one component's schema, addressed by the same file stem the
// fixture directories use, e.g. ReadSchema(FixturesBridgeProtocol).
func ReadSchema(name string) (Schema, error) {
	rel := path.Join("schemas", name+".json")
	raw, err := fs.ReadFile(FS(), rel)
	if err != nil {
		return Schema{}, fmt.Errorf("aslcontract: reading %s: %w", rel, err)
	}
	var schema Schema
	if err := json.Unmarshal(raw, &schema); err != nil {
		return Schema{}, fmt.Errorf("aslcontract: decoding %s: %w", rel, err)
	}
	return schema, nil
}

// Enum returns the declared values of one named definition, in schema order.
// It fails rather than returning an empty list when the definition is missing
// or carries no enum, because an absent vocabulary must not read as a
// vocabulary that happens to permit nothing.
func (s Schema) Enum(definition string) ([]string, error) {
	raw, ok := s.Definitions[definition]
	if !ok {
		return nil, fmt.Errorf("aslcontract: schema %s declares no %s", s.Component, definition)
	}
	var node struct {
		Enum []string `json:"enum"`
	}
	if err := json.Unmarshal(raw, &node); err != nil {
		return nil, fmt.Errorf("aslcontract: decoding %s.%s: %w", s.Component, definition, err)
	}
	if len(node.Enum) == 0 {
		return nil, fmt.Errorf("aslcontract: %s.%s is not an enum", s.Component, definition)
	}
	return node.Enum, nil
}

// Fixture is one canonical document plus the case metadata around it. Invalid
// fixtures additionally declare the reason and JSON pointer they must be
// rejected at, which is what keeps "rejected" from passing for the wrong cause.
type Fixture struct {
	Name        string          `json:"-"`
	Path        string          `json:"-"`
	Case        string          `json:"case"`
	Description string          `json:"description"`
	Root        string          `json:"root"`
	Reason      string          `json:"reason"`
	Pointer     string          `json:"pointer"`
	Document    json.RawMessage `json:"document"`
}

// ReadFixture loads one fixture, e.g.
// ReadFixture(FixturesBridgeProtocol, "valid", "hello").
func ReadFixture(component, validity, name string) (Fixture, error) {
	rel := path.Join("fixtures", component, validity, name+".json")
	raw, err := fs.ReadFile(FS(), rel)
	if err != nil {
		return Fixture{}, fmt.Errorf("aslcontract: reading %s: %w", rel, err)
	}
	var fixture Fixture
	if err := json.Unmarshal(raw, &fixture); err != nil {
		return Fixture{}, fmt.Errorf("aslcontract: decoding %s: %w", rel, err)
	}
	fixture.Name = name
	fixture.Path = rel
	return fixture, nil
}

// ReadFixtures loads every fixture in one component/validity directory, in
// ascending name order.
func ReadFixtures(component, validity string) ([]Fixture, error) {
	dir := path.Join("fixtures", component, validity)
	entries, err := fs.ReadDir(FS(), dir)
	if err != nil {
		return nil, fmt.Errorf("aslcontract: listing %s: %w", dir, err)
	}
	fixtures := make([]Fixture, 0, len(entries))
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".json") {
			continue
		}
		fixture, err := ReadFixture(component, validity, strings.TrimSuffix(entry.Name(), ".json"))
		if err != nil {
			return nil, err
		}
		fixtures = append(fixtures, fixture)
	}
	sort.Slice(fixtures, func(i, j int) bool { return fixtures[i].Name < fixtures[j].Name })
	return fixtures, nil
}

// PlaceholderContractSetID is the value fixture documents carry in place of a
// real ID. A fixture cannot embed the digest of its own bytes, so the corpus
// spells the field with a well-formed placeholder and the authoritative ID
// lives in the manifest. A consumer substitutes ContractSetID for it before
// comparing a fixture against live output.
const PlaceholderContractSetID = Prefix + "0000000000000000"
